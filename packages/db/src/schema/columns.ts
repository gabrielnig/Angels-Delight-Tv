import { sql } from 'drizzle-orm';
import { customType, timestamp, uuid } from 'drizzle-orm/pg-core';

export const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => 'bytea',
});

export const citext = customType<{ data: string }>({
  dataType: () => 'citext',
});

export const tsvector = customType<{ data: string }>({
  dataType: () => 'tsvector',
});

export const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

export const createdAt = () => timestamptz('created_at').notNull().defaultNow();
export const updatedAt = () => timestamptz('updated_at').notNull().defaultNow();

/** Primary key generated by the app as UUIDv7, with gen_random_uuid() as the database fallback. */
export const pk = () => uuid('id').primaryKey().defaultRandom();

export const SLUG_PATTERN = '^[a-z0-9]+(-[a-z0-9]+)*$';
export const slugCheck = (column: string) =>
  sql.raw(`${column} ~ '${SLUG_PATTERN}' AND char_length(${column}) BETWEEN 3 AND 120`);
