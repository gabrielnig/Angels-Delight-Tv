'use client';

import Link from 'next/link';
import { useActionState } from 'react';
import { Button, LinkButton } from '@/components/admin/Button';
import { TextField } from '@/components/admin/fields';
import { confirmEnrolmentAction } from '../actions';
import type { EnrolState } from '../actions';

interface Props {
  qrSvg: string;
  secret: string;
  next: string;
}

/** First sign in for staff: scan the code, confirm it, then save the recovery codes (M12-S02, M12-S03). */
export function EnrolForm({ qrSvg, secret, next }: Props) {
  const [state, action, pending] = useActionState<EnrolState, FormData>(confirmEnrolmentAction, {});

  if (state.recoveryCodes) {
    return (
      <div className="adm-stack">
        <p className="adm-muted" style={{ margin: 0 }}>
          Save these recovery codes somewhere safe. Each works once if you lose your phone. They are
          shown only now.
        </p>
        <ul
          aria-label="Recovery codes"
          className="adm-stack"
          style={{ listStyle: 'none', margin: 0, padding: 0 }}
        >
          {state.recoveryCodes.map((code) => (
            <li key={code}>
              <code>{code}</code>
            </li>
          ))}
        </ul>
        <LinkButton href={next} variant="primary">
          I have saved them, continue
        </LinkButton>
      </div>
    );
  }

  return (
    <form action={action} className="adm-stack">
      {/* Generated by our own QR encoder from the otpauth link, never from user input. */}
      <div
        role="img"
        aria-label="QR code for your authenticator app"
        // nosemgrep: react-dangerouslysetinnerhtml (SVG from our own QR encoder, no user input)
        dangerouslySetInnerHTML={{ __html: qrSvg }}
      />
      <p className="adm-muted" style={{ margin: 0 }}>
        Cannot scan? Enter this key in your app: <code>{secret}</code>
      </p>
      {state.error ? (
        <p role="alert" className="adm-field__error">
          {state.error}
        </p>
      ) : null}
      <TextField
        label="6 digit code"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        required
      />
      <Button type="submit" variant="primary" loading={pending}>
        Confirm and finish
      </Button>
      <Link href="/admin/login" className="adm-link">
        Back to sign in
      </Link>
    </form>
  );
}
